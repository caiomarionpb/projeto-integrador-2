-- =====================================================================
-- Trigger para a auditoria com o UPDATE
-- =====================================================================
CREATE OR REPLACE TRIGGER trg_report_grade -- Nome do trigger sendo criado
AFTER UPDATE OF grade ON Grade -- Trigger acontece depois de um UPDATE do atributo grade na tabela Grade
FOR EACH ROW -- Para cada uma das linhas
WHEN (NEW.grade <> OLD.grade) -- Em qualquer momento que a nota nova for maior ou menor do que a nota antiga
DECLARE -- É nessa seção que declaramos as variáveis que serão utilizadas e/ou salvas na auditoria
   -- Variáveis e seus tipos
   v_student_name VARCHAR2(150);
   v_id_professor NUMBER;
   v_message_log VARCHAR2(100);
   v_data_evento TIMESTAMP := CURRENT_TIMESTAMP; -- Explicando um operador não visto em aula: := é um operador de atribuição, indicando que o valor a ser colocado nessa variável é do tipo herdado do atribulo e de valor igual à data e horário do momento da execução
   v_data_hora_str VARCHAR2(30); -- VARCHAR que vai receber a data e hora acima formatada de acordo com o que for configurado
BEGIN -- Onde começa a operação do trigger
   -- Obtenção do nome do aluno inserido na variável v_student_name da tabela Student onde o id é o mesmo do id do UPDATE
   SELECT name INTO v_student_name
   FROM Student
   WHERE id = :NEW.id_student;

   -- Select que busca o id do professsor com base no componente de nota que foi alterado
   SELECT i.id_professor INTO v_id_professor
   FROM Grade_component gc
   JOIN Subject s ON gc.id_subject = s.id
   JOIN Course c ON s.id_course = c.id
   JOIN Institution i ON c.id_institution = i.id
   WHERE gc.id = :NEW.id_grade_component;

   -- Formatação da data/hora a partir do modelo fornecido no escopo, utilizando a variável que recebe o CURRENT_TIMESTAMP e modificando o formato
   v_data_hora_str := TO_CHAR(v_data_evento, 'DD/MM/YYYY HH24:MI:SS');

   -- Desenvolvimento da mensagem de alteração de acordo com o indicado pelos docentes no escopo do projeto
   v_message_log := ''|| v_data_hora_str || ' (Aluno ' || v_student_name || ') Nota de ' || :OLD.grade || ' para ' || :NEW.grade || ' modificada e salva!';

   -- Inserção das variáveis obtiddas dentro da tabela LOG_REPORT para registrar a ocorrência
   INSERT INTO LOG_REPORT
   (id_student, id_grade_component, old_grade, new_grade, date_time, message, id_grade, id_professor)
   VALUES
   (:NEW.id_student, :NEW.id_grade_component, :OLD.grade, :NEW.grade, v_data_evento, v_message_log, :NEW.id,v_id_professor);

   -- Exibir no Script Output a mensagem elaborada anteriormente
   DBMS_OUTPUT.PUT_LINE(v_message_log);

-- Tratamento da exceção caso ocorra algum erro no trigger
EXCEPTION
WHEN OTHERS THEN
   -- Exibe qual erro ocorreu dentro do Script Output
   DBMS_OUTPUT.PUT_LINE('Erro ao gravar o log de auditoria: ' || SQLERRM);
END;

COMMIT;


