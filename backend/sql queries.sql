-- Tabela Docentes
CREATE TABLE Professor
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   first_name VARCHAR2(20) NOT NULL,
   surname VARCHAR2(150),
   email VARCHAR2(200) NOT NULL,
   cell_number VARCHAR2(20) NOT NULL,
   password VARCHAR2(20) NOT NULL,
   UNIQUE (email, cell_number)
);
COMMIT;


-- Tabela Instituições
CREATE TABLE Institution
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(120) NOT NULL,
   id_professor NUMBER NOT NULL
);
COMMIT;


-- Tabela Cursos
CREATE TABLE Course
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(100) NOT NULL,
   id_institution NUMBER NOT NULL
);
COMMIT;
  
-- Tabela Disciplinas
CREATE TABLE Subject
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(120) NOT NULL,
   code VARCHAR2(10) NOT NULL,
   term VARCHAR2(30) NOT NULL,
   id_course NUMBER NOT NULL
);
COMMIT;


-- Tabela Turmas
CREATE TABLE Class
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(100) NOT NULL,
   day VARCHAR2(100) NOT NULL,
   time VARCHAR2(20) NOT NULL,
   building VARCHAR2(100) NOT NULL,
   classroom VARCHAR2(10) NOT NULL,
   id_subject NUMBER NOT NULL
);
COMMIT;


-- Tabela Alunos
CREATE TABLE Student
(
   id VARCHAR2(20) PRIMARY KEY,
   name VARCHAR2(150) NOT NULL
);
COMMIT;


-- Tabela Componentes de Nota
CREATE TABLE Grade_component
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   name VARCHAR2(100) NOT NULL,
   code VARCHAR2(4),
   description VARCHAR2(150),
   weight NUMBER,
   id_subject NUMBER NOT NULL
);
COMMIT;


-- Tabela Notas
CREATE TABLE Grade
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   grade NUMBER(4,2) NOT NULL,
   id_grade_component NUMBER NOT NULL,
   id_student VARCHAR2(20) NOT NULL
);
COMMIT;


-- Tabela Auditorias
CREATE TABLE LOG_REPORT
(
   id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   date_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
   old_grade NUMBER(4,2),
   new_grade NUMBER(4,2) NOT NULL,
   message VARCHAR2(100) NOT NULL,
   id_grade NUMBER NOT NULL,
   id_student VARCHAR2(20) NOT NULL,
   id_grade_component NUMBER NOT NULL,
   id_professor NUMBER NOT NULL
);
COMMIT;


-- Tabela Matrícula (entidade associativa entre Alunos e Turmas)
CREATE TABLE Registration
(
   PRIMARY KEY(id_class, id_student),
   id_class NUMBER NOT NULL,
   id_student VARCHAR2(20) NOT NULL
